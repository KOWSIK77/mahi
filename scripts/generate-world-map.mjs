// Generates the dotted world map (public/images/map/world-dots.svg) and the
// projected city coordinates (lib/world-map.data.ts) used by the Global Reach section.
// Run: node scripts/generate-world-map.mjs   (only needed when cities/region change)
import DottedMap from "dotted-map";
import { writeFileSync } from "node:fs";

const SCALE = 10; // overlay coordinate scale (map units x10)

const map = new DottedMap({
  height: 72,
  grid: "diagonal",
  region: { lat: { min: -50, max: 72 }, lng: { min: -125, max: 158 } },
});

// key, label, lat, lng, tier: origin | primary | secondary
const cities = [
  ["india", "India", 11.1, 77.34, "origin"],
  ["dubai", "UAE · Dubai", 25.2, 55.27, "primary"],
  ["lagos", "Nigeria · Lagos", 6.52, 3.38, "primary"],
  ["riyadh", "Saudi Arabia", 24.71, 46.68, "secondary"],
  ["cairo", "Egypt", 30.04, 31.24, "secondary"],
  ["nairobi", "Kenya", -1.29, 36.82, "secondary"],
  ["joburg", "South Africa", -26.2, 28.05, "secondary"],
  ["london", "United Kingdom", 51.5, -0.13, "secondary"],
  ["newyork", "USA", 40.71, -74.0, "secondary"],
  ["saopaulo", "Brazil", -23.55, -46.63, "secondary"],
  ["singapore", "Singapore", 1.35, 103.82, "secondary"],
  ["sydney", "Australia", -33.87, 151.21, "secondary"],
];

const out = cities.map(([key, label, lat, lng, tier]) => {
  const p = map.getPin({ lat, lng });
  return { key, label, tier, x: +(p.x * SCALE).toFixed(1), y: +(p.y * SCALE).toFixed(1) };
});

// Compact output: every dot is a zero-length segment drawn with a round cap (one <path>).
const d = map.getPoints().map((p) => `M${+p.x.toFixed(2)} ${+p.y.toFixed(2)}h0`).join("");
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${map.image.width} ${map.image.height}"><path d="${d}" stroke="#6F8AB5" stroke-width="0.5" stroke-linecap="round" fill="none"/></svg>`;
writeFileSync("public/images/map/world-dots.svg", svg);

const { width, height } = map.image;
writeFileSync(
  "lib/world-map.data.ts",
  `// GENERATED by scripts/generate-world-map.mjs — do not edit by hand.\n` +
    `export const MAP_WIDTH = ${width * SCALE};\nexport const MAP_HEIGHT = ${height * SCALE};\n` +
    `export type MapCity = { key: string; label: string; tier: "origin" | "primary" | "secondary"; x: number; y: number };\n` +
    `export const cities: MapCity[] = ${JSON.stringify(out, null, 2)};\n`,
);
console.log({ width, height, bytes: svg.length, cities: out.length });
